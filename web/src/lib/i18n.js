const DICTS = { en, es, hi, fr, ar, de, pt };

export function translate(locale, key, vars) {
  const dict = DICTS[locale] || en;
  let out = dict[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(new RegExp(`{${k}}`, 'g'), v);
  return out;
}

export const dirOf = (locale) => LOCALES.find((l) => l.code === locale)?.dir || 'ltr';
export const coverageOf = (locale) => Math.round((Object.keys(DICTS[locale] || {}).length / Object.keys(en).length) * 100);
